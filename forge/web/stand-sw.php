<?php
/**
 * stand-sw.php — the stand page's service worker, scoped to stand.php only.
 *
 * WHAT IT KEEPS, AND WHAT IT NEVER DOES.
 *   • The shell, first: stand.php (a page with no world in it, which is why
 *     it can be kept), the viewer script by its content hash, and the icon,
 *     put away on install. A navigation goes to the network and falls back
 *     to the kept shell when the box cannot be reached.
 *   • Panoramas, by fingerprint: a look's bytes route ends in the view's
 *     fingerprint, so the address IS the content — kept the first time it is
 *     fetched and served from the cache after, a dozen at most.
 *   • The API, never. Every other call to api.php goes to the network and
 *     fails when the network does. That failure is how the page knows it is
 *     offline, and it then shows the last room labelled "earlier" with every
 *     verb off. Nothing is queued: a line said now and delivered in an hour
 *     would be stamped into a different world hour than the one it answered.
 *
 * Its version is the content of the files it keeps (and of itself), so a
 * deploy that changes any of them installs a new worker and drops the old
 * shell. The panoramas are kept across versions: their addresses do not lie.
 *
 * Served as JavaScript from our own origin (the page's CSP says worker-src
 * 'self'); its own policy lets it fetch from this origin and nothing else.
 */

declare(strict_types=1);

$hash = static fn(string $f): string => substr((string)@hash_file('sha256', __DIR__ . '/' . $f), 0, 16);
$view = 'xeric-view.js?v=' . $hash('xeric-view.js');
$ver  = substr(hash('sha256', $hash('stand.php') . $hash('xeric-view.js') . $hash('stand-icon.png') . $hash('stand-sw.php')), 0, 16);

header('Content-Type: text/javascript; charset=utf-8');
header('Cache-Control: no-cache');
header('X-Content-Type-Options: nosniff');
header("Content-Security-Policy: default-src 'none'; connect-src 'self'");

$shell = ['stand.php', $view, 'stand-icon.png'];
?>
// The stand page's service worker. Generated by stand-sw.php; see its header.
'use strict';
var SHELL = 'xeric-stand-<?= $ver ?>';
var PANOS = 'xeric-stand-panos';
var KEEP = <?= json_encode($shell, JSON_UNESCAPED_SLASHES) ?>;
var MAX_PANOS = 12;

self.addEventListener('install', function (e) {
  // One at a time and each forgiven: a missing icon must not cost the shell.
  e.waitUntil(caches.open(SHELL).then(function (c) {
    return Promise.all(KEEP.map(function (u) {
      return fetch(u, { credentials: 'same-origin', cache: 'no-cache' }).then(function (r) {
        if (r.ok) return c.put(u, r);
      }).catch(function () {});
    }));
  }).then(function () { return self.skipWaiting(); }).catch(function () {}));
});

self.addEventListener('activate', function (e) {
  e.waitUntil(caches.keys().then(function (ks) {
    return Promise.all(ks.filter(function (k) {
      return k.indexOf('xeric-stand-') === 0 && k !== SHELL && k !== PANOS;
    }).map(function (k) { return caches.delete(k); }));
  }).then(function () { return self.clients.claim(); }).catch(function () {}));
});

// A look's bytes: api.php/v1/worlds/{w}/look/{k}/{fingerprint}, not a sound.
function isPano(url) {
  return /\/api\.php\/v1\/worlds\/[^/]+\/look\/[^/]+\/[0-9a-f]{8,}$/i.test(url.pathname);
}

self.addEventListener('fetch', function (e) {
  var req = e.request;
  if (req.method !== 'GET') return;
  var url = new URL(req.url);
  if (url.origin !== self.location.origin) return;

  if (isPano(url)) {
    var key = url.origin + url.pathname;
    e.respondWith(caches.open(PANOS).then(function (c) {
      return c.match(key).then(function (hit) {
        if (hit) return hit;
        return fetch(req).then(function (r) {
          if (r.ok) {
            c.put(key, r.clone()).then(function () {
              return c.keys().then(function (ks) {
                return Promise.all(ks.slice(0, Math.max(0, ks.length - MAX_PANOS)).map(function (k) { return c.delete(k); }));
              });
            }).catch(function () {});
          }
          return r;
        });
      });
    }));
    return;
  }

  // The API, always the network: nothing to respond with here.
  if (/\/api\.php(\/|$)/.test(url.pathname)) return;

  // The page itself: the network, and the kept shell when it is not there.
  // Any ?w= is the same shell — it carries no world.
  if (req.mode === 'navigate' && /\/stand\.php$/.test(url.pathname)) {
    e.respondWith(fetch(req).then(function (r) {
      if (r.ok) {
        var copy = r.clone();
        caches.open(SHELL).then(function (c) { return c.put('stand.php', copy); }).catch(function () {});
      }
      return r;
    }).catch(function () {
      return caches.open(SHELL).then(function (c) { return c.match('stand.php'); }).then(function (hit) {
        return hit || new Response('The machine cannot be reached.', { status: 503, headers: { 'Content-Type': 'text/plain' } });
      });
    }));
    return;
  }

  // The viewer by its hash, the icon, the manifest: kept copies first.
  e.respondWith(caches.open(SHELL).then(function (c) {
    return c.match(req).then(function (hit) { return hit || fetch(req); });
  }));
});
